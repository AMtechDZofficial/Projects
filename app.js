function applyLang(lang) {
  const t = translations[lang];
  if (!t) return;
  document.documentElement.lang = lang;
  document.documentElement.dir = t.dir;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (t[key] !== undefined) el.innerHTML = t[key];
  });
  document.querySelectorAll("[data-i18n-ph]").forEach((el) => {
    const key = el.getAttribute("data-i18n-ph");
    if (t[key] !== undefined) el.setAttribute("placeholder", t[key]);
  });
  if (t["page.title"]) document.title = t["page.title"];

  try { localStorage.setItem("amtech-lang", lang); } catch (e) {}
}

document.addEventListener("DOMContentLoaded", () => {
  // Année du footer
  const yearEl = document.getElementById("year");
  if (yearEl) yearEl.textContent = new Date().getFullYear();

  // Menu mobile
  const toggle = document.getElementById("navToggle");
  const nav = document.getElementById("nav");
  if (toggle && nav) {
    toggle.addEventListener("click", () => nav.classList.toggle("open"));
    nav.querySelectorAll("a").forEach((a) =>
      a.addEventListener("click", () => nav.classList.remove("open"))
    );
  }

  // Langue : préférence sauvegardée, sinon français
  let lang = "fr";
  try { lang = localStorage.getItem("amtech-lang") || "fr"; } catch (e) {}
  applyLang(lang);

  const langBtn = document.getElementById("langToggle");
  if (langBtn) {
    langBtn.addEventListener("click", () => {
      const current = document.documentElement.lang === "ar" ? "ar" : "fr";
      applyLang(current === "ar" ? "fr" : "ar");
    });
  }

  // Formulaire de contact (Formspree)
  const form = document.getElementById("contactForm");
  const status = document.getElementById("formStatus");
  if (form) {
    form.addEventListener("submit", async (e) => {
      e.preventDefault();
      const lang = document.documentElement.lang === "ar" ? "ar" : "fr";
      const t = translations[lang];
      const action = form.getAttribute("action") || "";

      status.textContent = t["form.sending"];
      status.className = "form-status sending";
      try {
        const res = await fetch(action, {
          method: "POST",
          body: new FormData(form),
          headers: { Accept: "application/json" },
        });
        if (res.ok) {
          status.textContent = t["form.success"];
          status.className = "form-status success";
          form.reset();
        } else {
          throw new Error("response not ok");
        }
      } catch (err) {
        status.textContent = t["form.error"];
        status.className = "form-status error";
      }
    });
  }
});
